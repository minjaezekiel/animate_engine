/**
 * Procedural textures, painted into an RGBA byte array.
 *
 * # Why this exists
 *
 * The 3D path had exactly one texture: `textTexture`, a slide drawn with a 2D
 * context. Every other surface in every 3D film in this repo is one flat
 * colour with a PBR roughness, which is the single largest reason a rendered
 * frame reads as a diagram rather than a photograph -- and it is why
 * [14-CHARACTER-3D.md](../../../docs/14-CHARACTER-3D.md) lists "UVs and
 * textures on the body" as still open after two phases of closing its
 * ceiling.
 *
 * The obvious fix is to load an image. That works, and `textures: { id: {
 * src } }` now does it. But an engine whose films are generated by a script
 * and checked into git cannot depend on somebody else's JPEG for its
 * *default* surface quality: the repo's whole bargain is that `git clone`
 * plus `npm run` reproduces the film byte for byte. So the primary path is
 * synthesis.
 *
 * # Why it returns bytes rather than a canvas
 *
 * `paintTexture` is pure arithmetic over a `Uint8ClampedArray`. It imports
 * neither THREE nor the DOM, so it is unit-tested in Node like every other
 * module in `core/` -- the same bargain `compile3d` makes. The browser side
 * is four lines: `putImageData`, `new CanvasTexture`. That matters because
 * texture synthesis is where the arithmetic bugs are (a seam at the date
 * line, a ramp that clips, a mask read off by one channel), and none of
 * those need a GPU to find.
 *
 * # The model: layers, not kinds
 *
 * A first pass had a texture `kind` per texture -- `noise`, `gradient`,
 * `earth`. That collapses the moment a surface needs two of them, which is
 * every real surface: an ocean gradient *under* continents *under* terrain
 * variation *under* ice. So a texture is a stack of layers composited in
 * order, each with a blend mode and an alpha, exactly like the paint stack
 * in [16-PAINT.md](../../../docs/16-PAINT.md) -- and `earth` stops being a
 * texture kind and becomes data a film passes in.
 */

/** Blend modes, per channel, on 0..1 floats. */
const BLEND = {
    normal: (_b, s) => s,
    multiply: (b, s) => b * s,
    screen: (b, s) => b + s - b * s,
    add: (b, s) => b + s,
    overlay: (b, s) => (b < 0.5 ? 2 * b * s : 1 - 2 * (1 - b) * (1 - s)),
    // Soft light, W3C/SVG form. The useful one for terrain variation: it
    // lightens and darkens without ever clipping to black or white, which
    // `overlay` does the moment the base is already dark.
    softLight: (b, s) => (s <= 0.5
        ? b - (1 - 2 * s) * b * (1 - b)
        : b + (2 * s - 1) * ((b <= 0.25 ? ((16 * b - 12) * b + 4) * b : Math.sqrt(b)) - b)),
};

const clamp01 = (v) => (v < 0 ? 0 : v > 1 ? 1 : v);
const smoothstep = (t) => t * t * (3 - 2 * t);
const lerp = (a, b, t) => a + (b - a) * t;

/**
 * '#rgb' | '#rrggbb' | '#rrggbbaa' -> [r, g, b, a] in 0..1.
 *
 * Returns magenta on anything unparseable rather than throwing, for the same
 * reason every diagnostic in this engine is a warning: one mistyped colour
 * should cost you a visible wrong surface, not a render.
 */
export function parseColor(input) {
    if (Array.isArray(input)) {
        return [clamp01(input[0] ?? 0), clamp01(input[1] ?? 0),
                clamp01(input[2] ?? 0), clamp01(input[3] ?? 1)];
    }
    const s = String(input ?? '').trim().replace(/^#/, '');
    const hex = s.length === 3 || s.length === 4
        ? [...s].map((c) => c + c).join('')
        : s;
    if (!/^[0-9a-f]{6}([0-9a-f]{2})?$/i.test(hex)) return [1, 0, 1, 1];
    const n = (i) => parseInt(hex.slice(i * 2, i * 2 + 2), 16) / 255;
    return [n(0), n(1), n(2), hex.length === 8 ? n(3) : 1];
}

/**
 * Sample a stop list at t. Stops are `[position, color]`, position 0..1.
 *
 * Unsorted stops are sorted rather than rejected: a ramp is easier to author
 * as "and also an ice line at 0.95" appended to the end than as a list kept
 * in order by hand.
 */
export function sampleRamp(stops, t) {
    if (!stops?.length) return [0, 0, 0, 1];
    const list = stops
        .map((s) => (Array.isArray(s) ? { at: s[0], color: parseColor(s[1]) }
                                      : { at: s.at ?? 0, color: parseColor(s.color) }))
        .sort((a, b) => a.at - b.at);
    const u = clamp01(t);
    if (u <= list[0].at) return list[0].color;
    if (u >= list[list.length - 1].at) return list[list.length - 1].color;
    for (let i = 1; i < list.length; i++) {
        if (u <= list[i].at) {
            const span = list[i].at - list[i - 1].at;
            const k = span <= 0 ? 0 : (u - list[i - 1].at) / span;
            const a = list[i - 1].color;
            const b = list[i].color;
            return [lerp(a[0], b[0], k), lerp(a[1], b[1], k),
                    lerp(a[2], b[2], k), lerp(a[3], b[3], k)];
        }
    }
    return list[list.length - 1].color;
}

/**
 * Integer hash to 0..1. A hash, not a generator.
 *
 * The same reason [13-3D-FILM.md §4](../../../docs/13-3D-FILM.md) gives for
 * particles: a generator carries state, state is history, and a texture that
 * depends on the order its pixels were visited is not reproducible. This is
 * a pure function of (seed, x, y), so any pixel can be painted alone and the
 * image comes out the same.
 */
function hash2(seed, x, y) {
    let h = (seed | 0) * 374761393 + (x | 0) * 668265263 + (y | 0) * 2147483647;
    h = (h ^ (h >>> 13)) * 1274126177;
    h ^= h >>> 16;
    return ((h >>> 0) % 0x1000000) / 0x1000000;
}

/**
 * Value noise on a lattice, bilinear with a smoothstep fade.
 *
 * `gx` is the lattice width and the sample wraps on it, which is the whole
 * point: an equirectangular texture meets itself at the date line, and
 * non-periodic noise puts a vertical seam down the Pacific that is visible
 * on every single frame of a rotating globe. It wraps in y as well, which
 * costs nothing and means a tiling surface tiles.
 */
export function valueNoise(seed, u, v, gx, gy) {
    const x = u * gx;
    const y = v * gy;
    const x0 = Math.floor(x);
    const y0 = Math.floor(y);
    const fx = smoothstep(x - x0);
    const fy = smoothstep(y - y0);
    const wrap = (n, m) => ((n % m) + m) % m;
    const h = (ix, iy) => hash2(seed, wrap(ix, gx), wrap(iy, gy));
    const a = lerp(h(x0, y0), h(x0 + 1, y0), fx);
    const b = lerp(h(x0, y0 + 1), h(x0 + 1, y0 + 1), fx);
    return lerp(a, b, fy);
}

/** Fractal sum of value noise. `ridged` folds it about 0.5 for crust and veins. */
export function fbm(u, v, {
    seed = 1, octaves = 4, scale = 4, lacunarity = 2, gain = 0.5, ridged = false,
} = {}) {
    let sum = 0;
    let norm = 0;
    let amp = 1;
    let gx = Math.max(1, Math.round(scale));
    let gy = Math.max(1, Math.round(scale / 2));
    for (let o = 0; o < octaves; o++) {
        let n = valueNoise(seed + o * 7919, u, v, gx, gy);
        if (ridged) n = 1 - Math.abs(n * 2 - 1);
        sum += n * amp;
        norm += amp;
        amp *= gain;
        gx = Math.max(1, Math.round(gx * lacunarity));
        gy = Math.max(1, Math.round(gy * lacunarity));
    }
    return norm > 0 ? sum / norm : 0;
}

/**
 * Is (u, v) inside any of these polygons?
 *
 * Even-odd crossing count. Polygons are `[[x, y], ...]` in the layer's own
 * coordinates: `equirect` takes degrees of longitude and latitude, `uv`
 * takes 0..1 directly.
 *
 * Crossings are counted with a half-open rule on y (`y0 <= y < y1`), which
 * is what stops a vertex exactly on the scanline from being counted twice
 * and punching a one-pixel hole through a coastline. That showed up as a
 * dotted line along the equator in Africa the first time.
 */
function insidePolygons(polys, x, y) {
    let inside = false;
    for (const poly of polys) {
        for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
            const [xi, yi] = poly[i];
            const [xj, yj] = poly[j];
            if ((yi <= y) !== (yj <= y)) {
                const t = (y - yi) / (yj - yi);
                if (x < xi + t * (xj - xi)) inside = !inside;
            }
        }
    }
    return inside;
}

/**
 * One layer's colour and coverage at (u, v).
 *
 * Returns `[r, g, b, coverage]`. Coverage is kept separate from the colour's
 * own alpha so a mask can be read off a layer that painted an opaque
 * continent: "where did this layer draw" and "how transparent was what it
 * drew" are different questions, and conflating them is why the first
 * terrain pass covered the oceans too.
 */
function layerAt(layer, u, v, ctx) {
    switch (layer.kind) {
        case 'solid': {
            const c = parseColor(layer.color);
            return [c[0], c[1], c[2], c[3]];
        }
        case 'gradient': {
            // `axis: 'y'` is the one an equirectangular planet wants: a
            // function of latitude. 'x' is longitude, 'radial' is distance
            // from `center` in uv.
            let t;
            if (layer.axis === 'radial') {
                const [cx, cy] = layer.center ?? [0.5, 0.5];
                const r = layer.radius ?? 0.5;
                t = Math.hypot(u - cx, v - cy) / (r || 1);
            } else if (layer.axis === 'x') {
                t = u;
            } else {
                t = v;
            }
            if (layer.mirror) t = 1 - Math.abs(t * 2 - 1);
            const c = sampleRamp(layer.stops, t);
            return [c[0], c[1], c[2], c[3]];
        }
        case 'noise': {
            const n = fbm(u, v, layer);
            const warped = layer.contrast
                ? clamp01((n - 0.5) * layer.contrast + 0.5)
                : n;
            const c = layer.stops
                ? sampleRamp(layer.stops, warped)
                : [warped, warped, warped, 1];
            return [c[0], c[1], c[2], c[3]];
        }
        case 'polygons': {
            const equirect = (layer.projection ?? 'equirect') === 'equirect';
            const x = equirect ? u * 360 - 180 : u;
            const y = equirect ? 90 - v * 180 : v;
            // A coastline straight off a polygon edge is a vector outline,
            // which reads as a map and not as a planet. `jitter` pushes the
            // test point by a little noise, which frays the edge at texel
            // scale without needing a second pass.
            const j = layer.jitter ?? 0;
            const dx = j ? (fbm(u, v, { seed: (layer.seed ?? 1) + 101, octaves: 3, scale: 64 }) - 0.5) * j : 0;
            const dy = j ? (fbm(u, v, { seed: (layer.seed ?? 1) + 211, octaves: 3, scale: 64 }) - 0.5) * j : 0;
            const hit = insidePolygons(layer.polygons ?? [], x + dx * (equirect ? 360 : 1),
                                       y + dy * (equirect ? 180 : 1));
            if (!hit) return [0, 0, 0, 0];
            const c = parseColor(layer.color);
            return [c[0], c[1], c[2], c[3]];
        }
        case 'latitudeBand': {
            // Ice caps and climate bands: coverage as a function of latitude
            // with a soft edge, which a gradient cannot do because it has to
            // compose over whatever is already there rather than replace it.
            const lat = 90 - v * 180;
            const edge = layer.feather ?? 6;
            const north = layer.north ?? 90;
            const south = layer.south ?? -90;
            const above = clamp01((lat - north) / edge + 1);
            const below = clamp01((south - lat) / edge + 1);
            const cov = Math.max(0, Math.max(above, below) - 0);
            if (cov <= 0) return [0, 0, 0, 0];
            const c = parseColor(layer.color);
            return [c[0], c[1], c[2], c[3] * cov];
        }
        case 'mask': {
            // Draws nothing; exists so a later layer can reference a shape
            // that is not itself visible. `coverage` carries through.
            const prior = ctx.masks.get(layer.from);
            const i = ctx.index;
            return [0, 0, 0, prior ? prior[i] : 0];
        }
        default:
            return [1, 0, 1, 1];
    }
}

/**
 * Paint a texture spec to RGBA bytes.
 *
 *   { width, height, background, layers: [ { kind, ... }, ... ] }
 *
 * Each layer may carry:
 *   `id`        a name later layers can mask by
 *   `alpha`     scales its coverage
 *   `blend`     normal | multiply | screen | add | overlay | softLight
 *   `mask`      an earlier layer's id; `!id` inverts it
 *   `maskSoft`  multiply the mask by this layer's own coverage instead of
 *               replacing it (the default is to multiply, which is what
 *               "terrain only on land" means)
 */
export function paintTexture(spec = {}) {
    const width = Math.max(1, Math.round(spec.width ?? 1024));
    const height = Math.max(1, Math.round(spec.height ?? 512));
    const data = new Uint8ClampedArray(width * height * 4);
    const bg = parseColor(spec.background ?? '#000000');

    const n = width * height;
    // Float accumulation buffers, converted to bytes once at the end. A
    // texture is composited in several passes and quantising to 8 bits
    // between each one banded every gradient that had a noise layer over it.
    const buf = new Float32Array(n * 4);
    for (let i = 0; i < n; i++) {
        buf[i * 4] = bg[0]; buf[i * 4 + 1] = bg[1];
        buf[i * 4 + 2] = bg[2]; buf[i * 4 + 3] = bg[3];
    }

    const masks = new Map();
    const ctx = { masks, index: 0 };

    for (const layer of spec.layers ?? []) {
        const blend = BLEND[layer.blend ?? 'normal'] ?? BLEND.normal;
        const alpha = layer.alpha ?? 1;
        /**
         * `mask` is one name or several, each optionally `!`-inverted, and
         * they MULTIPLY.
         *
         * One mask is not enough for anything real. A desert is "on land, and
         * away from the poles, and not on the equator" -- three conditions,
         * and with a single mask slot the only way to express it is to bake
         * latitude into the noise itself, which is what the first pass did
         * and why it scattered sand across Siberia. Intersecting named
         * coverages is the same composition rule the layers themselves use,
         * so it costs one loop and no new concept.
         */
        const maskRefs = (Array.isArray(layer.mask) ? layer.mask
            : layer.mask ? [layer.mask] : [])
            .map((m) => (String(m).startsWith('!')
                ? { mask: masks.get(String(m).slice(1)), invert: true }
                : { mask: masks.get(String(m)), invert: false }))
            .filter((m) => m.mask);
        const coverage = layer.id ? new Float32Array(n) : null;

        for (let y = 0; y < height; y++) {
            // Texel CENTRES, not corners. Sampling at v = y/height puts the
            // top row exactly on the north pole, where an equirectangular
            // map has zero width -- so the first row of a latitude gradient
            // was the pole colour across the entire image.
            const v = (y + 0.5) / height;
            for (let x = 0; x < width; x++) {
                const u = (x + 0.5) / width;
                const i = y * width + x;
                ctx.index = i;
                const [r, g, b, cov] = layerAt(layer, u, v, ctx);
                let a = cov * alpha;
                for (const m of maskRefs) a *= m.invert ? 1 - m.mask[i] : m.mask[i];
                // Coverage is recorded BEFORE alpha and before masking, so a
                // layer can define a shape without drawing it -- `alpha: 0`
                // plus an `id` is how a latitude zone becomes a mask for
                // something else to stop at.
                if (coverage) coverage[i] = cov;
                if (a <= 0) continue;
                const o = i * 4;
                buf[o] = lerp(buf[o], blend(buf[o], r), a);
                buf[o + 1] = lerp(buf[o + 1], blend(buf[o + 1], g), a);
                buf[o + 2] = lerp(buf[o + 2], blend(buf[o + 2], b), a);
                buf[o + 3] = Math.max(buf[o + 3], a);
            }
        }
        if (coverage) masks.set(layer.id, coverage);
    }

    for (let i = 0; i < n * 4; i++) data[i] = Math.round(clamp01(buf[i]) * 255);
    return { width, height, data };
}

/**
 * A normal map from a height texture, by central differences.
 *
 * Three.js `bumpMap` perturbs the normal from a greyscale image and costs
 * one texture; a real normal map costs the same and does not suffer the
 * bumpMap's dependence on screen-space derivatives. Generated here rather
 * than authored, because the height field is already generated and keeping
 * two hand-written versions of the same terrain in sync is not a thing
 * anyone does twice.
 *
 * Wraps in x, clamps in y: a sphere's texture meets itself at the date line
 * and does not meet itself across the pole.
 */
export function normalFromHeight({ width, height, data }, strength = 2) {
    const out = new Uint8ClampedArray(width * height * 4);
    const at = (x, y) => {
        const xx = ((x % width) + width) % width;
        const yy = y < 0 ? 0 : y >= height ? height - 1 : y;
        return data[(yy * width + xx) * 4] / 255;
    };
    for (let y = 0; y < height; y++) {
        for (let x = 0; x < width; x++) {
            const dx = (at(x + 1, y) - at(x - 1, y)) * strength;
            const dy = (at(x, y + 1) - at(x, y - 1)) * strength;
            // Tangent-space normal: (-dx, -dy, 1) normalised, then mapped
            // from -1..1 into 0..1 the way every normal map is stored.
            const len = Math.hypot(dx, dy, 1);
            const o = (y * width + x) * 4;
            out[o] = Math.round((-dx / len * 0.5 + 0.5) * 255);
            out[o + 1] = Math.round((-dy / len * 0.5 + 0.5) * 255);
            out[o + 2] = Math.round((1 / len * 0.5 + 0.5) * 255);
            out[o + 3] = 255;
        }
    }
    return { width, height, data: out };
}
